-- ItemStats.lua -- single source of truth for owned-gear stats.
--
-- PURE DATA + one pure helper. No windower.* calls, no GearSwap calls, so
-- this file loads in a standalone Lua interpreter for offline testing:
--     local stats = dofile('ItemStats.lua')
-- and in any GearSwap job lua (place it in the SAME FOLDER as the job luas;
-- GearSwap's include() searches the job file's directory first):
--     include('ItemStats.lua')   -- defines globals: item_stats, item_stat()
--
-- PROVENANCE: entries below were generated from Windower/Resources game data
-- (items.lua + item_descriptions.lua) for every Armor/Weapon item in the
-- character's full inventory export (Falurian, 2026-08-15), explicit post-export
-- player-confirmed acquisitions (Sakpata R0, 2026-08-16), plus everything
-- referenced in the job luas' sets -- the whole-account wardrobe, ready for
-- future job luas. 'augments' fields are verbatim from the export. 'desc' is the VERBATIM in-game description -- the ground truth
-- for secondary/tertiary stats when building sets. Numeric fields are parsed
-- from it mechanically, EXCEPT values marked 'hidden' (stats the description
-- only calls "Enhances ... effect"; community-tested numbers) and 'AUGMENT'
-- (this account's copy). Do not hand-edit generated numbers -- regenerate or
-- fix the desc first, so fields and desc never disagree.
--
-- UNITS (match the game engine / the job luas' convention):
--   fc  = Fast Cast %          dw    = Dual Wield pts
--   haste = gear haste in 1024ths (1% = 10.24; gear bucket caps at 256)
--   qm  = Quick Magic %        dt/mdt = Damage taken reduction %
--   stp = Store TP             da/ta  = Double/Triple Attack %
--   perp = Avatar perpetuation cost reduction (MP/tick)
--   bp_delay = "Blood Pact" ability delay reduction (sec; GEAR CAP 15)
--   bp_recast2 = "Blood Pact" recast time II reduction (sec; separate stat)
--   bp_dmg = "Blood Pact" damage +% (desc-sourced; excludes augments)
--   da_damage = Double Attack damage +%   berserk_duration = seconds
--   pdl = Physical Damage Limit +%   phalanx_received = flat received potency
-- v3.3.8 parser correction: Sroda Ring now exposes its desc-sourced pdl=3 field.
--   cure_received = Cure potency received %   counter = Counter %
--   meva = Magic Evasion       refresh = MP/tick    movement = speed %
--   enh_dur = Enhancing Magic duration %
--   jobs  = equippable jobs ('ALL' or 'RDM/NIN/...'), from the game's job
--           bitmask. CHECK THIS before recommending or slotting any piece --
--           the wardrobe spans every job on the account, and plausible-
--           looking gear (e.g. Sortie job earrings) is often job-locked.
--
-- KEYS are item names exactly as GearSwap reports them. Items whose stats
-- live in augments get "(path)" pseudo-keys -- see the Sucellos block.
